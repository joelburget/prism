"""Private fixture oracle: recompute selected valid SQL using SQLite.

Deliberately not an incremental implementation. Fixtures restrict SQL ordering to
explicit, deterministic ORDER BY (or a single global aggregate). SQLite is not the
oracle for the previous pilot's static type/error semantics. Those are retained as
fixed legacy regressions. No evaluated implementation may delegate SQL to SQLite.
"""
from copy import deepcopy
from contextlib import closing
import re
import sqlite3

class Fault(Exception):
    pass

def ident(x):
    return isinstance(x,str) and re.fullmatch(r'[a-z_][a-z0-9_]*',x) is not None

def vid(x):
    return isinstance(x,str) and re.fullmatch(r'[a-z][a-z0-9-]{0,39}',x) is not None

def valid_row(columns,row):
    if len(columns)!=len(row): return False
    for c,v in zip(columns,row):
        if v is None:
            if not c['nullable']: return False
        elif c['type']=='int':
            if type(v) is not int or not -1_000_000_000<=v<=1_000_000_000: return False
        elif c['type']=='bool':
            if type(v) is not bool: return False
        elif not isinstance(v,str): return False
    return True

class Model:
    def __init__(self,data):
        self.tables=deepcopy(data['database']); self.rows={t['name']:{i+1:r for i,r in enumerate(t['rows'])} for t in self.tables}
        self.used={n:set(r) for n,r in self.rows.items()}; self.views={}; self.revision=0

    def query(self,sql):
        with closing(sqlite3.connect(':memory:')) as db:
            for table in self.tables:
                # Quoted names, parameterized values; all fixtures have validated schema.
                columns=', '.join('"'+c['name']+'" '+{'int':'INTEGER','bool':'INTEGER','text':'TEXT'}[c['type']] for c in table['columns'])
                db.execute('CREATE TABLE "'+table['name']+'" ('+columns+')')
                slots=','.join('?' for _ in table['columns'])
                db.executemany('INSERT INTO "'+table['name']+'" VALUES ('+slots+')', self.rows[table['name']].values())
            cursor=db.execute(sql)
            return {'columns':[d[0] for d in cursor.description], 'rows':[list(r) for r in cursor.fetchall()]}

    def command(self,c):
        if not isinstance(c,dict): raise Fault('INVALID_COMMAND')
        op=c.get('op'); fields={'create':{'op','view','sql','optimize'},'read':{'op','view'},'drop':{'op','view'},'apply':{'op','changes'}}
        if not isinstance(op,str) or op not in fields or set(c)!=fields[op]: raise Fault('INVALID_COMMAND')
        if 'view' in c and not vid(c['view']): raise Fault('INVALID_COMMAND')
        if op=='create':
            if not isinstance(c['sql'],str) or type(c['optimize']) is not bool: raise Fault('INVALID_COMMAND')
            if c['view'] in self.views: raise Fault('VIEW_EXISTS')
            self.query(c['sql'])  # Only valid SQL is generated by this authoring oracle.
            self.views[c['view']]=c['sql']
            return {'view':c['view'],'revision':self.revision}
        if op in ('drop','read'):
            if c['view'] not in self.views: raise Fault('UNKNOWN_VIEW')
            if op=='drop': del self.views[c['view']]; return {'dropped':c['view']}
            return {'revision':self.revision,**self.query(self.views[c['view']])}
        changes=c['changes']
        if not isinstance(changes,list) or not 1<=len(changes)<=200: raise Fault('INVALID_COMMAND')
        for change in changes:
            if not isinstance(change,dict) or change.get('op') not in ('insert','update','delete'): raise Fault('INVALID_COMMAND')
            expected={'op','table','id'} | ({'row'} if change['op']!='delete' else set())
            if set(change)!=expected or not ident(change['table']) or type(change['id']) is not int or not 1<=change['id']<=2_147_483_647: raise Fault('INVALID_COMMAND')
            if 'row' in change and not isinstance(change['row'],list): raise Fault('INVALID_COMMAND')
        rows=deepcopy(self.rows); used=deepcopy(self.used)
        for change in changes:
            name=change['table']; rid=change['id']; kind=change['op']
            if name not in rows: raise Fault('UNKNOWN_TABLE')
            columns=next(t['columns'] for t in self.tables if t['name']==name)
            if kind!='delete' and not valid_row(columns,change['row']): raise Fault('INVALID_ROW')
            if kind=='insert':
                if rid in used[name]: raise Fault('ROW_ID_USED')
                used[name].add(rid); rows[name][rid]=change['row']
            else:
                if rid not in rows[name]: raise Fault('UNKNOWN_ROW')
                if kind=='update': rows[name][rid]=change['row']
                else: del rows[name][rid]
        self.rows=rows; self.used=used; self.revision+=1
        return {'revision':self.revision}

def evaluate(data):
    if not isinstance(data,dict) or set(data)!={'database','commands'} or not isinstance(data['commands'],list) or len(data['commands'])>2000:
        return {'ok':False,'error':{'code':'INVALID_INPUT'}}
    model=Model(data); results=[]
    for command in data['commands']:
        try: results.append({'ok':True,'result':model.command(command)})
        except Fault as e: results.append({'ok':False,'error':{'code':str(e)}})
    return {'ok':True,'result':{'results':results}}
